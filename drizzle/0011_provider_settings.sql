CREATE TABLE `provider_settings` (
	`id` integer PRIMARY KEY DEFAULT 1 NOT NULL,
	`revision` integer DEFAULT 1 NOT NULL,
	`spectra_region` text DEFAULT 'eu' NOT NULL,
	`spectra_host` text DEFAULT 'https://eu.valospectra.com' NOT NULL,
	`spectra_access_key_encrypted` text,
	`spectra_group_code` text DEFAULT '' NOT NULL,
	`gstack_url` text DEFAULT 'http://localhost:57780/' NOT NULL,
	`henrikdev_base_url` text DEFAULT 'https://api.henrikdev.xyz' NOT NULL,
	`henrikdev_api_key_encrypted` text,
	`henrikdev_affinity` text DEFAULT 'ap' NOT NULL,
	`henrikdev_platform` text DEFAULT 'pc' NOT NULL,
	`henrikdev_candidate_limit` integer DEFAULT 5 NOT NULL,
	`post_game_request_timeout_ms` integer DEFAULT 15000 NOT NULL,
	`spectra_post_game_base_url` text DEFAULT 'https://stats.valospectra.com' NOT NULL,
	`spectra_post_game_poll_interval_ms` integer DEFAULT 15000 NOT NULL,
	`spectra_post_game_max_attempts` integer DEFAULT 3 NOT NULL,
	`created_at` integer DEFAULT (unixepoch('subsecond') * 1000) NOT NULL,
	`updated_at` integer DEFAULT (unixepoch('subsecond') * 1000) NOT NULL,
	CONSTRAINT "provider_settings_singleton_check" CHECK ("provider_settings"."id" = 1),
	CONSTRAINT "provider_settings_revision_check" CHECK ("provider_settings"."revision" > 0),
	CONSTRAINT "provider_settings_henrikdev_candidate_limit_check" CHECK ("provider_settings"."henrikdev_candidate_limit" between 1 and 10),
	CONSTRAINT "provider_settings_post_game_timeout_check" CHECK ("provider_settings"."post_game_request_timeout_ms" between 1 and 30000),
	CONSTRAINT "provider_settings_spectra_poll_interval_check" CHECK ("provider_settings"."spectra_post_game_poll_interval_ms" between 1 and 15000),
	CONSTRAINT "provider_settings_spectra_max_attempts_check" CHECK ("provider_settings"."spectra_post_game_max_attempts" between 1 and 4)
);
